# 1. Arithmetic Operators

num1 = 10
num2 = 3

print("Arithmetic Operators:")

print("Addition:", num1 + num2)
print("Subtraction:", num1 - num2)
print("Multiplication:", num1 * num2)
print("Division:", num1 / num2)
print("Modulus:", num1 % num2)
print("Exponent:", num1 ** num2)
print("Floor Division:", num1 // num2)


# 2. Comparison Operators

print("\nComparison Operators:")

print("Equal to:", num1 == num2)
print("Not equal to:", num1 != num2)
print("Greater than:", num1 > num2)
print("Less than:", num1 < num2)
print("Greater than or equal to:", num1 >= num2)
print("Less than or equal to:", num1 <= num2)

# 3. Logical Operators

age = 20
has_id = True

print("\nLogical Operators:")

print("AND:", age >= 18 and has_id)
print("OR:", age >= 18 or has_id)
print("NOT:", not has_id)

# 4. Assignment Operators

number = 10

print("\nAssignment Operators:")

number += 5
print("After += :", number)

number -= 3
print("After -= :", number)

number *= 2
print("After *= :", number)

number /= 4
print("After /= :", number)

number %= 4
print("After %= :", number)

number **= 2
print("After **= :", number)

number //= 2
print("After //= :", number)
